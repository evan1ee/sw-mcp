"""Render the type model as Python dataclasses and C# classes (ADR-051)."""

import keyword
from collections.abc import Sequence

from contract_types import Field, Model, ObjectDef, TypeRef, pascal

HEADER = "Generated by scripts/generate_contracts.py from schemas/. Do not edit."
RETRYABLE_ENUM = "ErrorRetryable"

PY_PRELUDE = """from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from typing import Literal, Self, cast

from cad_ir.core.json_types import JsonValue

type Reader[T] = Callable[[JsonValue, str], T]


def _req(obj: dict[str, JsonValue], key: str, where: str) -> JsonValue:
    if key not in obj:
        raise ValueError(f"{where}.{key}: missing required field")
    return obj[key]


def _opt[T](obj: dict[str, JsonValue], key: str, where: str, read: Reader[T]) -> T | None:
    value = obj.get(key)
    return None if value is None else read(value, f"{where}.{key}")


def _any(value: JsonValue, where: str) -> JsonValue:
    del where
    return value


def _obj(value: JsonValue, where: str) -> dict[str, JsonValue]:
    if not isinstance(value, dict):
        raise ValueError(f"{where}: expected object")
    return value


def _arr(value: JsonValue, where: str) -> list[JsonValue]:
    if not isinstance(value, list):
        raise ValueError(f"{where}: expected array")
    return value


def _str(value: JsonValue, where: str) -> str:
    if not isinstance(value, str):
        raise ValueError(f"{where}: expected string")
    return value


def _bool(value: JsonValue, where: str) -> bool:
    if not isinstance(value, bool):
        raise ValueError(f"{where}: expected boolean")
    return value


def _int(value: JsonValue, where: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise ValueError(f"{where}: expected integer")
    return value


def _num(value: JsonValue, where: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{where}: expected number")
    return float(value)


def _list_of[T](read: Reader[T]) -> Reader[tuple[T, ...]]:
    def inner(value: JsonValue, where: str) -> tuple[T, ...]:
        return tuple(read(item, f"{where}[{i}]") for i, item in enumerate(_arr(value, where)))

    return inner


def _nullable[T](read: Reader[T]) -> Reader[T | None]:
    def inner(value: JsonValue, where: str) -> T | None:
        return None if value is None else read(value, where)

    return inner


def _dump(value: object) -> JsonValue:
    if isinstance(value, tuple):
        return [_dump(item) for item in cast("tuple[object, ...]", value)]
    to_json = getattr(value, "to_json", None)
    if callable(to_json):
        return cast("JsonValue", to_json())
    return cast("JsonValue", value)
"""

PY_READERS = {
    "string": "_str",
    "integer": "_int",
    "number": "_num",
    "boolean": "_bool",
    "opaque": "_any",
    "enum": "_str",
}
PY_ANNOTATIONS = {
    "string": "str",
    "integer": "int",
    "number": "float",
    "boolean": "bool",
    "opaque": "JsonValue",
}
CS_TYPES = {
    "string": "string",
    "integer": "long",
    "number": "double",
    "boolean": "bool",
    "opaque": "JToken",
}


def py_attr(json_name: str) -> str:
    name = json_name.lstrip("_") or json_name
    return name + "_" if keyword.iskeyword(name) else name


def cs_prop(json_name: str) -> str:
    return pascal(json_name.lstrip("_"))


def _py_annotation(t: TypeRef) -> str:
    if t.kind == "const":
        return f"Literal[{t.const!r}]"
    if t.kind in ("enum", "class"):
        return t.name
    if t.kind == "list" and t.item:
        return f"tuple[{_py_annotation(t.item)}, ...]"
    if t.kind == "nullable" and t.item:
        return f"{_py_annotation(t.item)} | None"
    return PY_ANNOTATIONS[t.kind]


def _py_reader(t: TypeRef) -> str:
    if t.kind == "const":
        return "_bool" if isinstance(t.const, bool) else "_str"
    if t.kind == "class":
        return f"{t.name}._at"
    if t.kind == "list" and t.item:
        return f"_list_of({_py_reader(t.item)})"
    if t.kind == "nullable" and t.item:
        return f"_nullable({_py_reader(t.item)})"
    return PY_READERS[t.kind]


def _py_field_line(f: Field) -> str:
    ann = _py_annotation(f.type)
    if f.type.kind == "const":
        return f"    {py_attr(f.json_name)}: {ann} = {f.type.const!r}"
    if f.required:
        return f"    {py_attr(f.json_name)}: {ann}"
    return f"    {py_attr(f.json_name)}: {ann} | None = None"


def _py_read_arg(f: Field) -> str:
    reader = _py_reader(f.type)
    key = f.json_name
    if not f.required:
        return f'{py_attr(key)}=_opt(obj, "{key}", where, {reader})'
    return f'{py_attr(key)}={reader}(_req(obj, "{key}", where), f"{{where}}.{key}")'


def _py_dump_lines(f: Field) -> list[str]:
    attr, key = py_attr(f.json_name), f.json_name
    if f.required:
        return [f'    out["{key}"] = _dump(self.{attr})']
    return [f"    if self.{attr} is not None:", f'        out["{key}"] = _dump(self.{attr})']


def _py_class(o: ObjectDef) -> list[str]:
    lines = ["", "", "@dataclass(frozen=True, slots=True, kw_only=True)", f"class {o.name}:"]
    lines += [_py_field_line(f) for f in o.fields] or ["    pass"]
    lines += [
        "",
        "    @classmethod",
        "    def from_json(cls, value: JsonValue) -> Self:",
        f'        return cls._at(value, "{o.name}")',
        "",
        "    @classmethod",
        "    def _at(cls, value: JsonValue, where: str) -> Self:",
        "        obj = _obj(value, where)",
        "        return cls(",
    ]
    lines += [f"            {_py_read_arg(f)}," for f in o.fields]
    lines += ["        )", "", "    def to_json(self) -> dict[str, JsonValue]:"]
    lines += ["        out: dict[str, JsonValue] = {}"]
    lines += [f"    {line}" for f in o.fields for line in _py_dump_lines(f)]
    lines += ["        return out"]
    return lines


def render_python(model: Model) -> str:
    lines = [f"# {HEADER}", '"""IPC message types generated from schemas/ipc/ (ADR-051)."""', ""]
    lines += PY_PRELUDE.splitlines()
    lines += ["", f'PROTOCOL_VERSION = "{model.protocol_version}"']
    for name, values in model.enums:
        members = ", ".join(repr(v) for v in values)
        lines += ["", f"type {name} = Literal[{members}]"]
    for name, t in model.aliases:
        if t.kind != "class":
            lines += ["", f"type {name} = {_py_annotation(t)}"]
    for o in model.objects:
        lines += _py_class(o)
    return "\n".join(lines) + "\n"


def _cs_type(t: TypeRef) -> str:
    if t.kind == "const":
        return "bool" if isinstance(t.const, bool) else "string"
    if t.kind in ("enum", "class"):
        return t.name
    if t.kind == "list" and t.item:
        return f"List<{_cs_type(t.item)}>"
    if t.kind == "nullable" and t.item:
        return f"{_cs_type(t.item)}?"
    return CS_TYPES[t.kind]


def _cs_initializer(t: TypeRef) -> str:
    if t.kind == "const":
        if isinstance(t.const, bool):
            return f" = {str(t.const).lower()};"
        return f' = "{t.const}";'
    if t.kind == "string":
        return " = string.Empty;"
    if t.kind == "list":
        return f" = new {_cs_type(t)}();"
    if t.kind in ("class", "opaque"):
        return " = null!;"
    return ""


def _cs_property(f: Field) -> list[str]:
    nullable = f.type.kind == "nullable"
    if not f.required:
        attr = "NullValueHandling = NullValueHandling.Ignore"
        decl = (
            f"public {_cs_type(f.type).removesuffix('?')}? {cs_prop(f.json_name)} {{ get; set; }}"
        )
    else:
        attr = f"Required = Required.{'AllowNull' if nullable else 'Always'}"
        decl = f"public {_cs_type(f.type)} {cs_prop(f.json_name)} {{ get; set; }}"
        decl += "" if nullable else _cs_initializer(f.type)
    return [f'    [JsonProperty("{f.json_name}", {attr})]', f"    {decl}"]


def _cs_enum(name: str, values: Sequence[str]) -> list[str]:
    lines = ["[JsonConverter(typeof(StringEnumConverter))]", f"public enum {name}", "{"]
    for i, value in enumerate(values):
        lines += [
            f'    [EnumMember(Value = "{value}")]',
            f"    {pascal(value)}{',' if i + 1 < len(values) else ''}",
        ]
    return [*lines, "}", ""]


def _cs_class(o: ObjectDef) -> list[str]:
    lines = [f"public sealed class {o.name}", "{"]
    for i, f in enumerate(o.fields):
        lines += ([""] if i else []) + _cs_property(f)
    return [*lines, "}", ""]


def _join_crlf(lines: Sequence[str]) -> str:
    return "\r\n".join(lines) + "\r\n"


def render_messages(model: Model) -> str:
    lines = [
        f"// {HEADER}",
        "// <auto-generated />",
        "#nullable enable",
        "using System.Collections.Generic;",
        "using System.Runtime.Serialization;",
        "using Newtonsoft.Json;",
        "using Newtonsoft.Json.Converters;",
        "using Newtonsoft.Json.Linq;",
        "",
        "namespace ExecutionServer.Core.Ipc.Generated;",
        "",
        "public static class ProtocolVersion",
        "{",
        f'    public const string Current = "{model.protocol_version}";',
        "}",
        "",
    ]
    for name, values in model.enums:
        lines += _cs_enum(name, values)
    for o in model.objects:
        lines += _cs_class(o)
    return _join_crlf(lines)


def render_error_codes(model: Model, pairs: Sequence[tuple[str, str]]) -> str:
    if RETRYABLE_ENUM not in dict(model.enums):
        raise SystemExit(
            f"schemas/common/v0.json: Error.retryable enum {RETRYABLE_ENUM} missing (ADR-051)"
        )
    lines = [
        f"// {HEADER}",
        "// <auto-generated />",
        "#nullable enable",
        "namespace ExecutionServer.Core.Ipc.Generated;",
        "",
        "public static class ErrorCodes",
        "{",
    ]
    lines += [f'    public const string {code} = "{code}";' for code, _ in pairs]
    lines += [
        "",
        "    /// <summary>Default retryable of a code; an unknown code is AfterFix.</summary>",
        f"    public static {RETRYABLE_ENUM} DefaultRetryable(string code)",
        "    {",
        "        switch (code)",
        "        {",
    ]
    for code, retryable in pairs:
        lines += [
            f"            case {code}:",
            f"                return {RETRYABLE_ENUM}.{pascal(retryable)};",
        ]
    lines += [
        "            default:",
        f"                return {RETRYABLE_ENUM}.AfterFix;",
        "        }",
        "    }",
        "}",
    ]
    return _join_crlf(lines)
