"""Embed `schemas/` and the error catalogue into `cad_ir.generated` (ADR-035, spec 3.4.8).

Usage: ``python scripts/generate_contracts.py [--check]``

Without arguments the generated files are (re)written. With ``--check`` nothing is written; the
stale paths are printed and the exit code is 1 when any output would differ.
"""

import argparse
import json
import pprint
from collections.abc import Sequence
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
GENERATED_DIR = Path("packages") / "cad-ir" / "src" / "cad_ir" / "generated"
ERRORS_ID_FILE = Path("schemas") / "common" / "errors.json"
HEADER = "# Generated by scripts/generate_contracts.py from schemas/. Do not edit."
RETRYABLE_VALUES = ("never", "after_fix", "safe")


def _load_schemas(root: Path) -> dict[str, Any]:
    """Every JSON file under ``schemas/``, keyed by its ``$id``, in sorted path order."""
    schemas: dict[str, Any] = {}
    for path in sorted((root / "schemas").rglob("*.json"), key=lambda p: p.as_posix()):
        doc = json.loads(path.read_text(encoding="utf-8"))
        schema_id = doc["$id"]
        if schema_id in schemas:
            raise SystemExit(f"duplicate $id {schema_id} ({path})")
        schemas[schema_id] = doc
    return schemas


def _load_catalogue(root: Path) -> list[tuple[str, str]]:
    """The ``(code, default retryable)`` pairs of ``errors.json`` in catalogue order."""
    doc = json.loads((root / ERRORS_ID_FILE).read_text(encoding="utf-8"))
    pairs: list[tuple[str, str]] = []
    for branch in doc["oneOf"]:
        code: str = branch["const"]
        retryable: str = branch["x-retryable"]
        if not code.isidentifier() or not code.isupper():
            raise SystemExit(f"error code {code!r} is not an UPPER_SNAKE_CASE identifier")
        if retryable not in RETRYABLE_VALUES:
            raise SystemExit(f"error code {code} has invalid x-retryable {retryable!r}")
        pairs.append((code, retryable))
    if len({code for code, _ in pairs}) != len(pairs):
        raise SystemExit("duplicate error codes in errors.json")
    return pairs


def _render_schemas(schemas: dict[str, Any]) -> str:
    body = pprint.pformat(schemas, sort_dicts=True, width=100)
    return (
        f"{HEADER}\n"
        '"""Every JSON Schema under schemas/, keyed by its $id."""\n'
        "\n"
        "from collections.abc import Mapping\n"
        "from types import MappingProxyType\n"
        "from typing import TYPE_CHECKING\n"
        "\n"
        "if TYPE_CHECKING:\n"
        "    from cad_ir.core.json_types import JsonValue\n"
        "\n"
        f'SCHEMAS: Mapping[str, "JsonValue"] = MappingProxyType(\n{body}\n)\n'
    )


def _render_error_codes(pairs: list[tuple[str, str]]) -> str:
    members = "".join(f'    {code} = "{code}"\n' for code, _ in pairs)
    defaults = "".join(f'        ErrorCode.{code}: "{retryable}",\n' for code, retryable in pairs)
    return (
        f"{HEADER}\n"
        '"""Error catalogue (ADR-037): codes and their default retryable values."""\n'
        "\n"
        "from collections.abc import Mapping\n"
        "from enum import StrEnum\n"
        "from types import MappingProxyType\n"
        "from typing import Literal\n"
        "\n"
        "\n"
        "class ErrorCode(StrEnum):\n"
        '    """Every error code, in catalogue order."""\n'
        "\n"
        f"{members}"
        "\n"
        '\ntype Retryable = Literal["never", "after_fix", "safe"]\n'
        "\n"
        "DEFAULT_RETRYABLE: Mapping[ErrorCode, Retryable] = MappingProxyType(\n"
        "    {\n"
        f"{defaults}"
        "    }\n"
        ")\n"
    )


def _render_init() -> str:
    return (
        f"{HEADER}\n"
        '"""Contracts generated from schemas/ (ADR-035)."""\n'
        "\n"
        "from cad_ir.generated.error_codes import ErrorCode\n"
        "\n"
        '__all__ = ["ErrorCode"]\n'
    )


def build_outputs(root: Path) -> dict[Path, str]:
    """Map each output path (relative to ``root``) to its full text."""
    return {
        GENERATED_DIR / "__init__.py": _render_init(),
        GENERATED_DIR / "error_codes.py": _render_error_codes(_load_catalogue(root)),
        GENERATED_DIR / "schemas.py": _render_schemas(_load_schemas(root)),
    }


def _stale(root: Path, outputs: dict[Path, str]) -> list[Path]:
    stale: list[Path] = []
    for relative, text in sorted(outputs.items(), key=lambda item: item[0].as_posix()):
        target = root / relative
        if not target.is_file() or target.read_bytes() != text.encode("utf-8"):
            stale.append(relative)
    return stale


def _orphans(root: Path, outputs: dict[Path, str]) -> list[Path]:
    """Python files in the generated directory that no output would write."""
    directory = root / GENERATED_DIR
    if not directory.is_dir():
        return []
    return sorted(
        (
            GENERATED_DIR / path.name
            for path in directory.glob("*.py")
            if GENERATED_DIR / path.name not in outputs
        ),
        key=lambda p: p.as_posix(),
    )


def main(argv: Sequence[str] | None = None, root: Path = REPO_ROOT) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if stale")
    args = parser.parse_args(argv)

    outputs = build_outputs(root)
    stale = _stale(root, outputs)
    orphans = _orphans(root, outputs)
    if args.check:
        for relative in stale:
            print(f"stale: {relative.as_posix()}")
        for relative in orphans:
            print(f"orphan: {relative.as_posix()}")
        if stale or orphans:
            print("run: uv run python scripts/generate_contracts.py")
        return 1 if stale or orphans else 0

    for relative in orphans:
        (root / relative).unlink()
        print(f"deleted: {relative.as_posix()}")

    for relative in stale:
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(outputs[relative].encode("utf-8"))
        print(f"wrote: {relative.as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
