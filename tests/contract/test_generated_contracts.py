"""The generated contract modules are in sync with `schemas/` and behave as specified."""

import importlib.util
import json
import shutil
import subprocess
import sys
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest
from cad_ir.generated import ErrorCode
from cad_ir.generated.error_codes import DEFAULT_RETRYABLE
from cad_ir.generated.schemas import SCHEMAS

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "generate_contracts.py"
HEADER = "# Generated by scripts/generate_contracts.py from schemas/. Do not edit."
GENERATED = ROOT / "packages" / "cad-ir" / "src" / "cad_ir" / "generated"
OUTPUT_NAMES = ("__init__.py", "error_codes.py", "schemas.py")


def _load_script() -> ModuleType:
    spec = importlib.util.spec_from_file_location("generate_contracts", SCRIPT)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _catalogue() -> list[dict[str, Any]]:
    doc = json.loads((ROOT / "schemas" / "common" / "errors.json").read_text(encoding="utf-8"))
    return doc["oneOf"]


def test_generated_up_to_date() -> None:
    result = subprocess.run(
        [sys.executable, str(SCRIPT), "--check"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr


def test_error_code_enum_matches_catalogue() -> None:
    branches = _catalogue()
    assert [member.name for member in ErrorCode] == [b["const"] for b in branches]
    assert [member.value for member in ErrorCode] == [b["const"] for b in branches]
    assert ErrorCode("REV_CONFLICT") is ErrorCode.REV_CONFLICT
    assert {code.value: DEFAULT_RETRYABLE[code] for code in ErrorCode} == {
        b["const"]: b["x-retryable"] for b in branches
    }
    assert set(DEFAULT_RETRYABLE) == set(ErrorCode)


def test_schemas_keyed_by_id() -> None:
    files = sorted((ROOT / "schemas").rglob("*.json"))
    loaded = {doc["$id"]: doc for doc in (json.loads(p.read_text(encoding="utf-8")) for p in files)}
    assert dict(SCHEMAS) == loaded
    assert "https://sw-mcp.invalid/schemas/common/v0.json" in SCHEMAS
    with pytest.raises(TypeError):
        SCHEMAS["x"] = {}  # type: ignore[index]  # pyright: ignore[reportIndexIssue]


def test_generated_files_have_header_and_lf_endings() -> None:
    for name in OUTPUT_NAMES:
        data = (GENERATED / name).read_bytes()
        assert data.startswith(HEADER.encode() + b"\n"), name
        assert b"\r" not in data, name


def test_check_detects_stale_and_write_fixes_it(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    script = _load_script()
    shutil.copytree(ROOT / "schemas", tmp_path / "schemas")
    (tmp_path / "packages" / "cad-ir" / "src" / "cad_ir").mkdir(parents=True)

    assert script.main(["--check"], root=tmp_path) == 1
    assert "schemas.py" in capsys.readouterr().out
    assert not (tmp_path / "packages" / "cad-ir" / "src" / "cad_ir" / "generated").exists()

    assert script.main([], root=tmp_path) == 0
    assert script.main(["--check"], root=tmp_path) == 0
    for name in OUTPUT_NAMES:
        written = (tmp_path / "packages/cad-ir/src/cad_ir/generated" / name).read_bytes()
        assert written == (GENERATED / name).read_bytes()

    (tmp_path / "packages/cad-ir/src/cad_ir/generated/error_codes.py").write_text("# stale\n")
    assert script.main(["--check"], root=tmp_path) == 1
    assert "error_codes.py" in capsys.readouterr().out


def test_orphan_generated_files_fail_check_and_are_deleted(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    script = _load_script()
    shutil.copytree(ROOT / "schemas", tmp_path / "schemas")
    generated = tmp_path / "packages/cad-ir/src/cad_ir/generated"
    generated.mkdir(parents=True)
    assert script.main([], root=tmp_path) == 0
    orphan = generated / "old_module.py"
    orphan.write_text("# left over")
    (generated / "__pycache__").mkdir()

    assert script.main(["--check"], root=tmp_path) == 1
    assert "orphan: packages/cad-ir/src/cad_ir/generated/old_module.py" in capsys.readouterr().out
    assert orphan.exists()

    assert script.main([], root=tmp_path) == 0
    assert not orphan.exists()
    assert script.main(["--check"], root=tmp_path) == 0
